app.get('/:imgParam', async function (req, res){
	const imgName = safeImageName(req.params.imgParam);
	if (!imgName) {
		console.log('rejected image name: ' + req.params.imgParam);
		return res.send({error:'no match'});
	}

	//content type is set explicitly rather than left to sendFile: some stored
	//images have no extension, and sendFile would label those
	//application/octet-stream, which makes browsers download instead of render.
	const contentType = contentTypeFor(imgName);

	//tier 1: local disk
	const localPath = __dirname + imagesDir + imgName;
	res.set('X-Content-Type-Options', 'nosniff');
	if (fs.existsSync(localPath)) {
		res.set('Cache-Control', CACHE_CONTROL);
		res.type(contentType);
		return res.sendFile(localPath);
	}

	//tier 2: object storage, which also holds everything that used to live on the
	//old mounted volume. Server-to-bucket traffic stays inside the Hetzner
	//network zone, so it is free and only costs one internal round trip.
	if (s3) {
		try {
			const obj = await s3.getObject({
				Bucket: config.OBJ_BUCKET,
				Key: imgName
			}).promise();
			res.set('Cache-Control', CACHE_CONTROL);
			res.type(contentType);
			return res.send(obj.Body);
		} catch (err) {
			if (err.code !== 'NoSuchKey' && err.statusCode !== 404) {
				console.error('bucket fetch failed for ' + imgName + ':', err.message);
			}
		}
	}

	console.log('no match for ' + imgName);
	return res.send({error:'no match'});
})


