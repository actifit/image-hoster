//images are immutable once written - the filename is a UUID generated by the
//client - so they can be cached indefinitely.
const CACHE_CONTROL = 'public, max-age=31536000, immutable';

const CONTENT_TYPES = {
	'.jpg': 'image/jpeg',
	'.jpeg': 'image/jpeg',
	'.png': 'image/png',
	'.gif': 'image/gif',
	'.webp': 'image/webp'
};

function contentTypeFor(fileName) {
	return CONTENT_TYPES[path.extname(fileName).toLowerCase()] || 'image/jpeg';
}

//the image name lands directly in filesystem paths, so anything that could climb
//out of the images directory has to be rejected. Express decodes %2F into a real
//slash after route matching, so "..%2F..%2Fetc%2Fpasswd" would otherwise reach
//fs/sendFile as a traversal.
function safeImageName(requested) {
	if (typeof requested !== 'string' || requested.length === 0 || requested.length > 255) {
		return null;
	}
	if (requested !== path.basename(requested)) {
		return null;
	}
	if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(requested)) {
		return null;
	}
	return requested;
}

//copy a file that is already on local disk into the bucket. Never throws: a
//storage outage must not fail an upload that has already been written to disk.
async function pushToBucket(filePath, key) {
	if (!s3) {
		return false;
	}
	try {
		await s3.putObject({
			Bucket: config.OBJ_BUCKET,
			Key: key,
			Body: fs.createReadStream(filePath),
			ContentType: contentTypeFor(key),
			CacheControl: CACHE_CONTROL
		}).promise();
		console.log('pushed to bucket: ' + key);
		return true;
	} catch (err) {
		console.error('failed pushing ' + key + ' to bucket:', err.message);
		return false;
	}
}

//where an image with this name already exists: 'local', 'bucket' or false.
//null when the bucket could not be checked: the caller must not publish then,
//so an outage can never let an upload replace a stored image.
async function imageExists(name) {
	if (fs.existsSync(path.join(__dirname, imagesDir, name))) {
		return 'local';
	}
	if (!s3) {
		return false;
	}
	try {
		await s3.headObject({ Bucket: config.OBJ_BUCKET, Key: name }).promise();
		return 'bucket';
	} catch (err) {
		if (err.code === 'NotFound' || err.code === 'NoSuchKey' || err.statusCode === 404) {
			return false;
		}
		console.error('bucket lookup failed for ' + name + ':', err.message);
		return null;
	}
}

async function sameFile(a, b) {
	try {
		const [x, y] = await Promise.all([fs.promises.readFile(a), fs.promises.readFile(b)]);
		return x.equals(y);
	} catch (err) {
		return false;
	}
}

//publish the processed temporary file under its final name. A hard link fails
//if that name exists, so a concurrent upload of the same name cannot replace it.
async function publishUpload(tmpPath, finalPath) {
	try {
		await fs.promises.link(tmpPath, finalPath);
		return true;
	} catch (err) {
		if (err.code === 'EEXIST') {
			return false;
		}
		throw err;
	}
}


function verifySecretKey(req, res, next) {
  const token = req.headers['authorization'];

  if (token !== secretKey && token !== secondSecretKey) {
    return res.status(403).send('Unauthorized access. Invalid token.');
  }

  next();
}

// Helper: Universally handles image orientation for all formats.
async function fixOrientationAndStripExif(filePath) {
  try {
    // 1. Read the original file into a buffer. This works for any format.
    const originalBuffer = await fs.promises.readFile(filePath);

    // 2. Read the orientation, falling back to the raw EXIF bytes when sharp
    //    cannot parse the EXIF block (see orientation.js).
    const { metadata, orientation } = await imageOrientation(originalBuffer);

    // 3. Physically rotate/mirror it upright. null means it already is.
    //    Sharp keeps the original format (JPEG, etc.).
    const rotatedBuffer = await uprightBuffer(originalBuffer, orientation);
    if (!rotatedBuffer) {
      console.log(`Image ${filePath} (format: ${metadata.format}) does not require rotation. File left untouched.`);
      return {
        rotated: false,
        orientation: orientation,
        metadataBefore: metadata
      };
    }
    if (!metadata.orientation) {
      console.log(`Image ${filePath}: sharp could not read the EXIF block; orientation ${orientation} read from raw EXIF.`);
    }
    console.log(`Image ${filePath} (format: ${metadata.format}) has orientation tag ${orientation}. Rotating upright.`);

    // 4. Overwrite the original file with the new, corrected buffer.
    await fs.promises.writeFile(filePath, rotatedBuffer);

    console.log(`Successfully rotated and saved ${filePath}.`);

    return {
      rotated: true,
      orientation: orientation,
      metadataBefore: metadata
    };

  } catch (err) {
    console.error(`CRITICAL: An error occurred during orientation check for ${filePath}.`, err);
    throw err;
  }
}


